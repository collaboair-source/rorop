export const ACTIVITIES: ActivityDef[] = RAW;

const BY_ID = new Map<ActivityId, ActivityDef>(ACTIVITIES.map((a) => [a.id, a]));

export function getActivity(id: ActivityId): ActivityDef {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`알 수 없는 활동: ${id}`);
  return found;
}

export function findActivity(id: string): ActivityDef | null {
  return BY_ID.get(id as ActivityId) ?? null;
}
